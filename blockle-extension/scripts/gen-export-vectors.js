// scripts/gen-export-vectors.js — author docs/wallet-export-vectors.json FROM
// the reference implementation (wallet-export.js), so the cross-wallet contract
// is exactly what the reference derives. Run: node scripts/gen-export-vectors.js
'use strict';
const fs = require('fs');
const path = require('path');
const WX = require('../wallet-export.js');

// A FIXED, well-known BIP-39 test mnemonic (all-zero entropy) — stable across
// every wallet. No funds should ever be sent here.
const MNEMONIC = 'abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about';
const PASSPHRASE = '';
const INDEX = 0;
const TIME = '2024-01-01T00:00:00Z';

const { seedHex, seed } = WX.fromMnemonic(MNEMONIC, PASSPHRASE);
const keys = WX.privateKeys(seed, INDEX);

const dumps = {};
for (const c of ['bitcoin', 'litecoin', 'dogecoin']) {
  dumps[c] = {
    filename: WX.coreDumpFilename(c),
    text: WX.coreDump(c, seed, { indices: [INDEX], time: TIME }),
  };
}

const vectors = {
  _comment: 'AUTHORITATIVE cross-wallet export contract. Generated by blockle-extension/scripts/gen-export-vectors.js from the reference wallet-export.js. The Dart + Python wallets MUST reproduce these exact values. FIXED test mnemonic (all-zero entropy) — never fund these addresses.',
  mnemonic: MNEMONIC,
  passphrase: PASSPHRASE,
  seedHex,
  accountIndex: INDEX,
  dumpTime: TIME,
  dangerWarning: WX.DANGER_WARNING,
  paths: {
    bitcoin: keys.bitcoin.path,
    litecoin: keys.litecoin.path,
    dogecoin: keys.dogecoin.path,
    evm: keys.evm.path,
    solana: keys.solana.path,
  },
  keys: {
    bitcoin: { address: keys.bitcoin.address, wif: keys.bitcoin.wif, wifVersion: keys.bitcoin.wifVersion, publicKey: keys.bitcoin.publicKey },
    litecoin: { address: keys.litecoin.address, wif: keys.litecoin.wif, wifVersion: keys.litecoin.wifVersion, publicKey: keys.litecoin.publicKey },
    dogecoin: { address: keys.dogecoin.address, wif: keys.dogecoin.wif, wifVersion: keys.dogecoin.wifVersion, publicKey: keys.dogecoin.publicKey },
    evm: { address: keys.evm.address, privateKey: keys.evm.privateKey, publicKey: keys.evm.publicKey },
    solana: { address: keys.solana.address, secretKey: keys.solana.secretKey, publicKey: keys.solana.publicKey },
  },
  coreDumps: dumps,
};

const out = path.resolve(__dirname, '..', '..', 'docs', 'wallet-export-vectors.json');
fs.writeFileSync(out, JSON.stringify(vectors, null, 2) + '\n');
console.log('wrote ' + out);
