// ton_test.dart — the TON adapter gate for the Flutter port.
//
// TON is the hardest chain: the v4R2 address IS cellHash(StateInit) and the
// signature signs cellHash(signingCell), so every value cascades from the cell
// representation hash. This test asserts, against the SHARED cross-port vector
// (regenerated from the canonical extension engine and cross-checked against
// @ton/ton + PyNaCl), that the Dart port reproduces every value byte-identically:
//   (a) SLIP-0010 ed25519 m/44'/607'/0' seed + ed25519 public key.
//   (b) the v4R2 code / data / StateInit cell hashes (pinned SEPARATELY so a bad
//       augmentation fails at the innermost cell, not at the address).
//   (c) the bounceable / non-bounceable / testnet / raw address round-trips.
//   (d) crc16 + crc32c KATs; isTonAddress accepts base64url + raw, rejects
//       EVM/BTC/SOL.
//   (e) cellHash(signing cell) + the ed25519 signature over it (+ verify).
//   (f) serializeBoc(signed external message) byte-exact + its hash.
//   (g) the jetton transfer body op + full jetton ext-msg BOC byte-exact.
// No network: the toncenter transport is injected for the buildSend check.
import 'dart:convert';
import 'dart:io';

import 'package:blockle_app/multichain/chains/chain_adapter.dart';
import 'package:blockle_app/multichain/chains/ton.dart' as ton;
import 'package:blockle_app/multichain/chains/ton_cell.dart' as tc;
import 'package:blockle_app/multichain/crypto/crypto_core.dart' as c;
import 'package:blockle_app/multichain/crypto/ed25519.dart' as ed;
import 'package:blockle_app/multichain/crypto/hd.dart' as hd;
import 'package:flutter_test/flutter_test.dart';

String h(List<int> b) => c.bytesToHex(b);

// The shared golden vector lives at the repo root (generated by the canonical
// extension engine). Tests run with cwd == blockle-app/, so '../docs/…'. The
// full docs vector carries the rich tx/jettonTx shape this gate asserts.
Map<String, dynamic> _loadVectors() {
  for (final p in ['../docs/ton-vectors.json']) {
    final f = File(p);
    if (f.existsSync()) {
      return jsonDecode(f.readAsStringSync()) as Map<String, dynamic>;
    }
  }
  throw StateError('ton vector not found (../docs/ton-vectors.json)');
}

void main() {
  final V = _loadVectors();
  final seed = hd.mnemonicToSeed(V['mnemonic'] as String, V['passphrase'] as String? ?? '');
  final path = V['path'] as String;
  final key = V['key'] as Map<String, dynamic>;
  final v4 = V['v4r2'] as Map<String, dynamic>;
  final tx = V['tx'] as Map<String, dynamic>;
  final jtx = V['jettonTx'] as Map<String, dynamic>;

  final keyBytes = ton.deriveSlip10Key(seed, path);
  final pub = ed.publicKey(keyBytes);

  group('discoverTokens: jetton auto-detect over a mocked jetton index', () {
    ton.TonAdapter adapter(String body) =>
        ton.TonAdapter(jettonIndex: 'http://x', get: (p) async => body);

    test('TON API shape {balances:[{balance,jetton:{…}}]} maps to Balances',
        () async {
      final body = jsonEncode({
        'balances': [
          {
            'balance': '3000000',
            'jetton': {
              'address': 'EQCxE6mUtQJKFnGfaROTKOt1lZbDiiX1kCixRv7Nw2Id_sDs',
              'symbol': 'USDT',
              'decimals': 6,
              'name': 'Tether USD'
            }
          }
        ]
      });
      final rows = await adapter(body).discoverTokens('EQOwner');
      expect(rows.length, 1);
      final b = rows.first;
      expect(b.asset.chain, 'ton');
      expect(b.asset.kind, 'jetton');
      expect(b.asset.address, 'EQCxE6mUtQJKFnGfaROTKOt1lZbDiiX1kCixRv7Nw2Id_sDs');
      expect(b.asset.symbol, 'USDT');
      expect(b.asset.decimals, 6);
      expect(b.confirmed, '3000000');
      expect(b.display, '3');
    });

    test('toncenter v3 shape {jetton_wallets, metadata} maps to Balances',
        () async {
      final body = jsonEncode({
        'jetton_wallets': [
          {'balance': '4200000', 'jetton': 'EQMaster000000000000000000000000000000AAA'}
        ],
        'metadata': {
          'EQMaster000000000000000000000000000000AAA': {
            'token_info': [
              {'symbol': 'SCALE', 'decimals': 9, 'name': 'Scaleton'}
            ]
          }
        }
      });
      final rows = await adapter(body).discoverTokens('EQOwner');
      expect(rows.length, 1);
      expect(rows.first.asset.symbol, 'SCALE');
      expect(rows.first.asset.decimals, 9);
      expect(rows.first.asset.address, 'EQMaster000000000000000000000000000000AAA');
      expect(rows.first.confirmed, '4200000');
    });

    test('zero balances skipped; empty => []; a network throw => []', () async {
      final zero = jsonEncode({
        'balances': [
          {
            'balance': '0',
            'jetton': {'address': 'EQZero', 'symbol': 'Z', 'decimals': 9}
          }
        ]
      });
      expect(await adapter(zero).discoverTokens('EQ'), isEmpty);
      expect(await adapter(jsonEncode({'balances': []})).discoverTokens('EQ'),
          isEmpty);
      final thrower =
          ton.TonAdapter(jettonIndex: 'http://x', get: (p) async => throw StateError('net'));
      expect(await thrower.discoverTokens('EQ'), isEmpty);
    });
  });

  group('(a) SLIP-0010 ed25519 derivation', () {
    test('seed + public key match the golden vector', () {
      expect(h(keyBytes), key['ed25519Seed32Hex']);
      expect(h(pub), key['publicKeyHex']);
    });
    test('deriveAccount yields the bounceable address + ed25519 scheme', () async {
      final a = ton.TonAdapter();
      final acct = await a.deriveAccount(RootSecret(seed: seed));
      expect(acct.address, v4['addressBounceable']);
      expect(acct.publicKey, key['publicKeyHex']);
      expect(acct.scheme, 'ed25519');
      expect(acct.path, path);
    });
  });

  group('(b) v4R2 cell hashes (pinned separately)', () {
    test('code cell hash == canonical WalletV4R2 code hash', () {
      expect(tc.v4r2CodeCell().hashHex(), v4['codeCellHashHex']);
    });
    test('data cell hash', () {
      expect(tc.v4r2DataCell(pub).hashHex(), v4['dataCellHashHex']);
    });
    test('StateInit cell hash == account hash == raw address', () {
      final si = tc.v4r2StateInit(pub);
      expect(si.hashHex(), v4['stateInitCellHashHex']);
      expect('0:${si.hashHex()}', v4['rawAddress']);
    });
  });

  group('(c) address codec', () {
    test('friendly encodings match (bounceable / non-bounceable / testnet)', () {
      final hash = tc.v4r2StateInit(pub).hash();
      expect(tc.formatAddress(0, hash), v4['addressBounceable']);
      expect(tc.formatAddress(0, hash, bounceable: false), v4['addressNonBounceable']);
      expect(tc.formatAddress(0, hash, testOnly: true), v4['addressTestnet']);
      expect(tc.rawAddress(0, hash), v4['rawAddress']);
    });
    test('bounceable decodes back to the raw hash', () {
      final a = tc.parseAddress(v4['addressBounceable'] as String);
      expect(tc.rawAddress(a.workchain, a.hash), v4['rawAddress']);
      expect(a.workchain, 0);
    });
    test('raw 0:hex round-trips to friendly', () {
      final a = tc.parseAddress(v4['rawAddress'] as String);
      expect(tc.formatAddress(a.workchain, a.hash), v4['addressBounceable']);
    });
    test('addressSpecVectors round-trip both directions', () {
      for (final pair in V['addressSpecVectors'] as List) {
        final raw = pair[0] as String;
        final friendly = pair[1] as String;
        final pr = tc.parseAddress(raw);
        expect(tc.formatAddress(pr.workchain, pr.hash), friendly);
        final pf = tc.parseAddress(friendly);
        expect(tc.rawAddress(pf.workchain, pf.hash), raw);
      }
    });
  });

  group('(d) crc KATs + isTonAddress', () {
    test('crc16/XMODEM + crc32c known-answer tests', () {
      final kats = V['crcKats'] as Map<String, dynamic>;
      for (final kat in kats['crc16ccitt'] as List) {
        final b = tc.crc16Ccitt(c.utf8Bytes(kat[0] as String)); // 2 bytes BE
        final v = (b[0] << 8) | b[1];
        expect('0x${v.toRadixString(16).padLeft(4, '0')}', kat[1]);
      }
      for (final kat in kats['crc32c'] as List) {
        final b = tc.crc32c(c.utf8Bytes(kat[0] as String)); // 4 bytes LE
        final v = (b[3] << 24) | (b[2] << 16) | (b[1] << 8) | b[0];
        expect('0x${(v & 0xffffffff).toRadixString(16).padLeft(8, '0')}', kat[1]);
      }
    });
    test('accepts base64url + raw, rejects EVM/BTC/SOL', () {
      expect(tc.isTonAddress(v4['addressBounceable'] as String), true);
      expect(tc.isTonAddress(v4['addressNonBounceable'] as String), true);
      expect(tc.isTonAddress(v4['rawAddress'] as String), true);
      expect(tc.isTonAddress('0x52908400098527886E0F7030069857D2E4169EE7'), false);
      expect(tc.isTonAddress('1BvBMSEYstWetqTFn5Au4m4GFg7xJaNVN2'), false);
      expect(tc.isTonAddress('So11111111111111111111111111111111111111112'), false);
    });
  });

  group('(e)+(f) native send: signing hash + signature + BOC byte-exact', () {
    final built = ton.buildNativeExternal(
      pubKey: pub,
      seedKey: keyBytes,
      dest: tc.parseAddress(tx['dest'] as String),
      amount: tx['amount'] as String,
      bounce: tx['bounce'] as bool,
      comment: tx['comment'] as String,
      seqno: tx['seqno'] as int,
      validUntil: tx['validUntil'] as int,
    );
    final exp = tx['expected'] as Map<String, dynamic>;

    test('internal + signing cell hashes match', () {
      expect(built.internalMsg.hashHex(), tx['internalMsgCellHashHex']);
      expect(built.signingCell.hashHex(), tx['signingCellHashHex']);
    });
    test('ed25519 signature over the signing-cell hash matches + verifies', () {
      expect(h(built.signature), exp['signatureHex']);
      expect(ed.verify(built.signingCell.hash(), built.signature, pub), true);
    });
    test('external message BOC is BYTE-EXACT + hash matches', () {
      expect(built.boc, exp['externalMessageBocBase64']);
      expect(built.hash, exp['externalMessageBocHashHex']);
    });
  });

  group('(g) jetton send: transfer body op + full ext-msg BOC byte-exact', () {
    final built = ton.buildJettonExternal(
      pubKey: pub,
      seedKey: keyBytes,
      jettonWallet: tc.parseAddress(jtx['ownerJettonWallet'] as String),
      dest: tc.parseAddress(jtx['dest'] as String),
      response: tc.parseAddress(jtx['responseDest'] as String),
      amount: jtx['amount'] as String,
      fwdAmount: jtx['fwdAmount'] as String,
      gas: jtx['attachTon'] as String,
      seqno: jtx['seqno'] as int,
      validUntil: jtx['validUntil'] as int,
    );
    final exp = jtx['expected'] as Map<String, dynamic>;

    test('transfer body op == 0x0f8a7ea5 + body/internal/signing hashes', () {
      expect(ton.jettonTransferOp, 0x0f8a7ea5);
      expect(built.jettonBody!.hashHex(), jtx['transferBodyCellHashHex']);
      expect(built.internalMsg.hashHex(), jtx['internalMsgCellHashHex']);
      expect(built.signingCell.hashHex(), jtx['signingCellHashHex']);
    });
    test('signature + full jetton external message BOC byte-exact', () {
      expect(h(built.signature), exp['signatureHex']);
      expect(ed.verify(built.signingCell.hash(), built.signature, pub), true);
      expect(built.boc, exp['externalMessageBocBase64']);
      expect(built.hash, exp['externalMessageBocHashHex']);
    });
  });

  group('adapter wiring', () {
    test('native asset: ton, 9 decimals; explorer deep-link', () {
      final a = ton.TonAdapter();
      expect(a.id, 'ton');
      expect(a.native.decimals, 9);
      expect(a.explorerTx('abc'), 'https://tonviewer.com/transaction/abc');
    });
    test('BOC decode round-trips the external message cell', () {
      final built = ton.buildNativeExternal(
        pubKey: pub,
        seedKey: keyBytes,
        dest: tc.parseAddress(tx['dest'] as String),
        amount: tx['amount'] as String,
        bounce: tx['bounce'] as bool,
        comment: tx['comment'] as String,
        seqno: tx['seqno'] as int,
        validUntil: tx['validUntil'] as int,
      );
      final decoded = tc.parseBoc(tc.tonFromBase64(built.boc))[0];
      expect(decoded.hashHex(), built.external.hashHex());
    });
    test('buildSend (generic client-built path) reproduces the golden BOC', () async {
      // Inject a toncenter transport that answers seqno=0 — the only node input.
      Future<String> post(String path, String body) async {
        return jsonEncode({
          'ok': true,
          'result': {
            'stack': [
              ['num', '0x0']
            ]
          }
        });
      }

      final a = ton.TonAdapter(post: post);
      a.unlock(RootSecret(seed: seed));
      final acct = await a.deriveAccount(RootSecret(seed: seed));
      final built = await a.buildSend(
        acct,
        SendRequest(to: tx['dest'] as String, amount: tx['amount'] as String),
      );
      final exp = tx['expected'] as Map<String, dynamic>;
      expect(built.raw, exp['externalMessageBocBase64']); // signed BOC byte-exact
      expect(built.txid, exp['externalMessageBocHashHex']);
      expect(built.extra?['kind'], 'send');
      expect(built.extra?['seqno'], 0);
    });
  });
}
